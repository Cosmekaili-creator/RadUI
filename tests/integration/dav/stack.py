"""Throwaway PRODUCTION-plugin stack for the store integration tests.

Radicale loaded with the production rights plugin (``backend/plugin``), whose users and rights files are
generated by the REAL backend (``backend/radui_admin``), plus the backend itself. Everything is loopback only,
on ports 15430-15439 (Radicale) and 15440-15449 (backend), in a directory under the git-ignored
``.throwaway/``. Nothing here touches a system service or system path. Passwords are random and are written
to ``<dir>/passwords`` (mode 600), never printed. Names are placeholders (alice, bob, agent-1, example.org).

Accounts: ``alice`` (administrator, own space), ``bob`` (person, own space), ``agent-1`` (bot, read-only
grants). No collection exists at start: every test creates its own through DAV and grants through the API.

Usage::

    stack.py run [--] COMMAND...     start the stack, run COMMAND with the environment below, tear down
    stack.py serve ENV_FILE          start the stack, write the environment to ENV_FILE, wait for SIGTERM

Environment given to the command:

    RADUI_TEST_PROD_RADICALE         http://127.0.0.1:<port>            (Radicale)
    RADUI_TEST_PROD_API              http://127.0.0.1:<port>            (backend)
    RADUI_TEST_PROD_API_BASE         path prefix of the account service (``/ui/api``)
    RADUI_TEST_PROD_API_ORIGIN       the Origin the backend accepts for mutating calls
    RADUI_TEST_PROD_PASSWORDS_FILE   ``login:password`` lines

Needs ``RADICALE_BIN`` (also read from ``.env.local``) and a Python with ``bcrypt``.
"""
import argparse
import os
import signal
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, os.path.join(REPO, "backend", "tests", "integration"))

import harness as H  # noqa: E402

RADICALE_PORTS = range(15430, 15440)
BACKEND_PORTS = range(15440, 15450)
BASE = os.path.join(REPO, ".throwaway", "dav-prod")
LOGINS = ("alice", "bob", "agent-1")


class DavStack(H.Stack):
    """``harness.Stack`` on the DAV integration ports and directory."""

    def __init__(self, name, *, max_connections=32, cfg=None):
        self.max_connections = max_connections
        saved = (H.RADICALE_PORTS, H.BACKEND_PORTS, H.BASE_DIR)
        H.RADICALE_PORTS, H.BACKEND_PORTS, H.BASE_DIR = RADICALE_PORTS, BACKEND_PORTS, BASE
        try:
            super().__init__(name, cfg=cfg)
        finally:
            H.RADICALE_PORTS, H.BACKEND_PORTS, H.BASE_DIR = saved

    def _write_radicale_conf(self):
        super()._write_radicale_conf()
        with open(self.radicale_conf) as fh:
            text = fh.read()
        text = text.replace("max_connections = 24", "max_connections = %d" % self.max_connections)
        with open(self.radicale_conf, "w") as fh:
            fh.write(text)

    def make_user(self, login):
        r = self.api("POST", "/accounts", "alice",
                     {"login": login, "displayName": login.title(), "type": "person", "admin": False, "generate": True})
        if r.status != 201:
            raise RuntimeError("create %s: %s" % (login, r.status))
        self.pw[login] = r.json["password"]


def start():
    if not H.support.RADICALE_BIN or not H.support.radicale_python():
        raise SystemExit("stack.py: Radicale not found (set RADICALE_BIN or .env.local)")
    avail = 0
    try:
        with open("/proc/meminfo") as fh:
            for line in fh:
                if line.startswith("MemAvailable:"):
                    avail = int(line.split()[1]) // 1024
    except OSError:
        pass
    if avail < 2048:
        raise SystemExit("stack.py: less than 2 GB memory available (%d MB)" % avail)
    stack = DavStack("dav-prod", cfg={"bcrypt_cost": 4})
    try:
        stack.up()
        stack.make_user("bob")
        for login in ("alice", "bob"):  # the principal is created on the first request of an own-space account
            r = stack.dav("PROPFIND", "/", login, headers={"Depth": "0"})
            if r.status != 207:
                raise RuntimeError("principal of %s: %s" % (login, r.status))
        pw_file = os.path.join(stack.dir, "passwords")
        fd = os.open(pw_file, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as fh:
            for login in LOGINS:
                fh.write("%s:%s\n" % (login, stack.pw[login]))
    except BaseException:
        stack.close()
        raise
    env = {
        "RADUI_TEST_PROD_RADICALE": "http://127.0.0.1:%d" % stack.rport,
        "RADUI_TEST_PROD_API": "http://127.0.0.1:%d" % stack.bport,
        "RADUI_TEST_PROD_API_BASE": H.PREFIX,
        "RADUI_TEST_PROD_API_ORIGIN": H.ORIGIN,
        "RADUI_TEST_PROD_PASSWORDS_FILE": pw_file,
    }
    return stack, env


def _on_signal(signum, frame):  # noqa: ARG001
    raise SystemExit(128 + signum)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    run = sub.add_parser("run")
    run.add_argument("command", nargs=argparse.REMAINDER)
    serve = sub.add_parser("serve")
    serve.add_argument("env_file")
    args = ap.parse_args()
    signal.signal(signal.SIGTERM, _on_signal)
    signal.signal(signal.SIGINT, _on_signal)
    stack, env = start()
    try:
        if args.cmd == "run":
            cmd = [c for c in args.command if c != "--"] if args.command[:1] == ["--"] else args.command
            if not cmd:
                raise SystemExit("stack.py run: no command")
            return subprocess.call(cmd, env=dict(os.environ, **env), cwd=REPO)
        fd = os.open(args.env_file, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as fh:
            for k, v in env.items():
                fh.write("export %s=%s\n" % (k, v))
        print("ready", flush=True)
        signal.pause()
        return 0
    finally:
        stack.close()


if __name__ == "__main__":
    sys.exit(main())

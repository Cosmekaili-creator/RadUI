"""Generate the service-worker file list (sw-manifest.js) for the static app.

Lists every file under the source directory (default: src/) with its SHA-256, except:
  sw.js, sw-manifest.js, package.json   (at the top level of the source directory)
  .gitkeep, README.md                   (anywhere)
  SHA256SUMS                            (anywhere below vendor/)

`config.json` (at the top level) is deployment-specific: the live copy differs from the one in the
source tree, so it is listed WITHOUT a hash ("sha256": null). The worker serves it network-first and
does not verify it.

The version is the first 16 hex digits of the SHA-256 over the sorted entries, each written as
`<path> NUL <sha256 or empty> LF` (UTF-8). The output is deterministic: the same tree gives
byte-identical output, whatever the order of the directory listing.

Usage:  build-sw-manifest.py [--src DIR] [--out FILE]
  --src DIR   directory to list (default: <repository>/src)
  --out FILE  file to write (default: <src>/sw-manifest.js); tests and E2E runs write into a run directory

Python standard library only.
"""
import argparse
import hashlib
import json
import os
import sys

TAG = "SPDX-License-Identifier: AGPL-3.0-or-later"
ROOT_EXCLUDED = {"sw.js", "sw-manifest.js", "package.json"}
ANYWHERE_EXCLUDED = {".gitkeep", "README.md"}
UNPINNED = {"config.json"}  # listed without a hash (deployment-specific file)
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SRC = os.path.join(os.path.dirname(HERE), "src")


def excluded(rel):
    parts = rel.split("/")
    name = parts[-1]
    if len(parts) == 1 and name in ROOT_EXCLUDED:
        return True
    if name in ANYWHERE_EXCLUDED:
        return True
    if name == "SHA256SUMS" and parts[0] == "vendor":
        return True
    return False


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def collect(src):
    """Sorted list of {'path', 'sha256'} for the files of `src` (posix-style relative paths)."""
    entries = []
    for dirpath, dirnames, filenames in os.walk(src):
        dirnames.sort()
        for name in filenames:
            full = os.path.join(dirpath, name)
            if os.path.islink(full) or not os.path.isfile(full):
                continue
            rel = os.path.relpath(full, src).replace(os.sep, "/")
            if excluded(rel):
                continue
            entries.append({"path": rel, "sha256": None if rel in UNPINNED else sha256_file(full)})
    entries.sort(key=lambda e: e["path"])
    return entries


def version_of(entries):
    digest = hashlib.sha256()
    for e in sorted(entries, key=lambda e: e["path"]):
        digest.update(e["path"].encode("utf-8") + b"\0" + (e["sha256"] or "").encode("ascii") + b"\n")
    return digest.hexdigest()[:16]


def render(entries):
    lines = [
        "// " + TAG,
        "// Generated by tools/build-sw-manifest.py from the files of the static app. Do not edit; not stored in git.",
        "self.RADUI_SW_MANIFEST = Object.freeze({",
        '  "version": %s,' % json.dumps(version_of(entries)),
        '  "files": [',
    ]
    rows = [
        "    " + json.dumps({"path": e["path"], "sha256": e["sha256"]}, separators=(", ", ": "))
        for e in entries
    ]
    lines.append(",\n".join(rows))
    lines.append("  ]")
    lines.append("});")
    return "\n".join(lines) + "\n"


def build(src, out):
    entries = collect(src)
    if not any(e["path"] == "index.html" for e in entries):
        raise SystemExit("build-sw-manifest: %s has no index.html (wrong --src?)" % src)
    text = render(entries)
    out_dir = os.path.dirname(os.path.abspath(out))
    os.makedirs(out_dir, exist_ok=True)
    tmp = out + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    os.replace(tmp, out)
    return version_of(entries), len(entries)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate sw-manifest.js (service-worker file list).")
    ap.add_argument("--src", default=DEFAULT_SRC, help="directory to list (default: src/)")
    ap.add_argument("--out", default=None, help="file to write (default: <src>/sw-manifest.js)")
    args = ap.parse_args(argv)
    src = os.path.abspath(args.src)
    if not os.path.isdir(src):
        raise SystemExit("build-sw-manifest: not a directory: %s" % src)
    out = os.path.abspath(args.out) if args.out else os.path.join(src, "sw-manifest.js")
    version, count = build(src, out)
    print("sw-manifest: %d files, version %s -> %s" % (count, version, out))
    return 0


if __name__ == "__main__":
    sys.exit(main())

def mkcol_book(name="b"):
    return ('<?xml version="1.0"?><D:mkcol %s><D:set><D:prop>'
            '<D:resourcetype><D:collection/><CR:addressbook/></D:resourcetype>'
            '<D:displayname>%s</D:displayname></D:prop></D:set></D:mkcol>'
            % (NS, name))


def mkcalendar(name="c", comp="VEVENT"):
    return ('<?xml version="1.0"?><C:mkcalendar %s><D:set><D:prop>'
            '<D:displayname>%s</D:displayname>'
            '<C:supported-calendar-component-set><C:comp name="%s"/>'
            '</C:supported-calendar-component-set></D:prop></D:set>'
            '</C:mkcalendar>' % (NS, name, comp))



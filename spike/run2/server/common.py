def card30(uid, fn="Jane Doe", extra=""):
    return ("BEGIN:VCARD\r\nVERSION:3.0\r\nUID:%s\r\nFN:%s\r\nN:%s;%s;;;\r\n%s"
            "END:VCARD\r\n" % (uid, fn, fn.split()[-1], fn.split()[0], extra))


def card40(uid, fn="Jane Doe", extra=""):
    return ("BEGIN:VCARD\r\nVERSION:4.0\r\nUID:%s\r\nFN:%s\r\nN:%s;%s;;;\r\n%s"
            "END:VCARD\r\n" % (uid, fn, fn.split()[-1], fn.split()[0], extra))


def event(uid, summary="Event"):
    return ("BEGIN:VCALENDAR\r\nVERSION:2.0\r\nPRODID:-//RadUI spike//EN\r\n"
            "BEGIN:VEVENT\r\nUID:%s\r\nDTSTAMP:20260101T000000Z\r\n"
            "DTSTART:20260601T100000Z\r\nDTEND:20260601T110000Z\r\n"
            "SUMMARY:%s\r\nEND:VEVENT\r\nEND:VCALENDAR\r\n" % (uid, summary))


# -- parsing helpers ------------------------------------------------------------

def unfold(text):
    """RFC 6350/5545 unfolding; returns the logical lines."""
    text = text.replace("\r\n", "\n")
    text = re.sub(r"\n[ \t]", "", text)
    return [ln for ln in text.split("\n") if ln != ""]


def multistatus(body):
    """``{href: {"status": str, "etag": str|None, "data": str|None}}``."""
    import xml.etree.ElementTree as ET
    D = "{DAV:}"
    try:
        root = ET.fromstring(body)
    except ET.ParseError:
        return {}
    out = {}
    for r in root.iter(D + "response"):
        href = r.find(D + "href").text
        ent = {"status": None, "etag": None, "data": None}
        st = r.find(D + "status")
        if st is not None:
            ent["status"] = st.text
        for ps in r.iter(D + "propstat"):
            pst = ps.find(D + "status")
            if pst is not None and ent["status"] is None:
                ent["status"] = pst.text
            for el in ps.find(D + "prop"):
                tag = el.tag.split("}")[1]
                if tag == "getetag":
                    ent["etag"] = el.text
                elif tag in ("address-data", "calendar-data"):
                    ent["data"] = el.text
        out[href] = ent
    return out


def sync_token(body):
    import xml.etree.ElementTree as ET
    try:
        root = ET.fromstring(body)
    except ET.ParseError:
        return None
    t = root.find("{DAV:}sync-token")
    return t.text if t is not None else None


def error_names(body):
    """Condition element names of a DAV:error body (e.g. valid-sync-token)."""
    import xml.etree.ElementTree as ET
    try:
        root = ET.fromstring(body)
    except ET.ParseError:
        return []
    if not root.tag.endswith("error"):
        return []
    return [c.tag.split("}")[1] for c in root]


def free_mb():
    with open("/proc/meminfo") as fh:
        for ln in fh:
            if ln.startswith("MemAvailable:"):
                return int(ln.split()[1]) // 1024
    return 0


def require_memory(min_mb=2000):
    if free_mb() < min_mb:
        print("less than %d MB of memory available: not starting" % min_mb,
              file=sys.stderr)
        sys.exit(2)



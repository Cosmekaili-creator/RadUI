"""Shared helpers of the RadUI Run 2 server spikes (S2-1 ... S2-10).

Everything here drives a *throwaway* stack only: Radicale 3.x loaded with the
PRODUCTION rights plugin (``backend/plugin``), whose users and rights files are
generated by the REAL backend (``backend/radui_admin``), all on loopback ports
15400-15409 (Radicale 15400-15404, backend 15405-15409), in a directory under
the git-ignored ``.throwaway/run2/``. Nothing here touches a system service or
system path. Passwords are random and never printed. Names are placeholders
(alice, bob, agent-1, example.org).

Standard layout (``standard_stack``):

* ``alice``   administrator; owns the address book ``contacts`` and the
              calendar ``cal-work``.
* ``bob``     read-write grant on ``alice/contacts`` and ``alice/cal-work``;
              also owns ``bob/bob-book`` and ``bob/bob-cal`` (a NON-admin owner).
* ``agent-1`` read grant on ``alice/contacts`` and ``alice/cal-work``.

Environment: ``RADICALE_BIN`` (also read from ``.env.local``).
"""

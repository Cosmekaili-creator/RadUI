def sync_body(token, props="<D:getetag/>"):
    tok = ("<D:sync-token>%s</D:sync-token>" % token) if token \
        else "<D:sync-token/>"
    return ('<?xml version="1.0"?><D:sync-collection %s>%s'
            '<D:sync-level>1</D:sync-level><D:prop>%s</D:prop>'
            '</D:sync-collection>' % (NS, tok, props))


def multiget_body(hrefs, data_tag="CR:address-data"):
    items = "".join("<D:href>%s</D:href>" % h for h in hrefs)
    ns = "CR" if "CR:" in data_tag else "C"
    root = "CR:addressbook-multiget" if ns == "CR" else "C:calendar-multiget"
    return ('<?xml version="1.0"?><%s %s><D:prop><D:getetag/><%s/></D:prop>%s'
            '</%s>' % (root, NS, data_tag, items, root))


class Checker:
    """PASS / FAIL / INFO lines with the observed evidence.

    ``expect`` is the plan's assumption (or the safe behaviour the code relies
    on): PASS when observed behaviour matches, FAIL when it contradicts.
    ``info`` is an observation without an assumption behind it.
    """

    def __init__(self, title):
        self.title = title
        self.passes = self.fails = self.infos = 0
        print("== %s ==" % title, flush=True)

    def expect(self, name, ok, evidence=""):
        if ok:
            self.passes += 1
        else:
            self.fails += 1
        print("%s %s :: %s" % ("PASS" if ok else "FAIL", name, evidence),
              flush=True)
        return ok

    def info(self, name, evidence=""):
        self.infos += 1
        print("INFO %s :: %s" % (name, evidence), flush=True)

    def finish(self):
        print("== %s: %d PASS, %d FAIL, %d INFO ==" % (
            self.title, self.passes, self.fails, self.infos), flush=True)
        return 1 if self.fails else 0


def short(data, n=160):
    """Printable one-line excerpt of a body (bytes or str)."""
    if isinstance(data, bytes):
        data = data.decode("utf-8", "replace")
    data = data.replace("\r\n", "\\r\\n").replace("\n", "\\n")
    return data if len(data) <= n else data[:n] + "...(%d chars)" % len(data)


class SpikeStack(H.Stack):
    """``harness.Stack`` on the Run 2 ports and directory."""

    def __init__(self, name, *, max_connections=24, cfg=None):
        self.max_connections = max_connections
        saved = (H.RADICALE_PORTS, H.BACKEND_PORTS, H.BASE_DIR)
        H.RADICALE_PORTS, H.BACKEND_PORTS, H.BASE_DIR = (
            RADICALE_PORTS, BACKEND_PORTS, BASE)
        try:
            super().__init__(name, cfg=cfg)
        finally:
            H.RADICALE_PORTS, H.BACKEND_PORTS, H.BASE_DIR = saved

    def _write_radicale_conf(self):
        super()._write_radicale_conf()
        with open(self.radicale_conf) as fh:
            text = fh.read()
        text = text.replace("max_connections = 24",
                            "max_connections = %d" % self.max_connections)
        with open(self.radicale_conf, "w") as fh:
            fh.write(text)

    def storage_root(self):
        return os.path.join(self.dir, "collections", "collection-root")

    def make_user(self, login, *, admin=False, bot=False, **kw):
        body = {"login": login, "displayName": login.title(),
                "type": "bot" if bot else "person", "admin": admin,
                "generate": True}
        body.update(kw)
        r = self.api("POST", "/accounts", "alice", body)
        if r.status != 201:
            raise RuntimeError("create %s: %s" % (login, r.status))
        self.pw[login] = r.json["password"]

    # -- DAV with timing and the Run 2 conventions ------------------------
    def req(self, method, path, login, body=None, headers=None, timeout=120):
        h = dict(headers or {})
        if login is not None:
            h["Authorization"] = H.basic(login, self.pw[login])
        if isinstance(body, str):
            body = body.encode("utf-8")
        t0 = time.monotonic()
        conn = http.client.HTTPConnection("127.0.0.1", self.rport,
                                          timeout=timeout)
        try:
            conn.request(method, path, body=body, headers=h)
            r = conn.getresponse()
            data = r.read()
            return Resp(r.status, {k.lower(): v for k, v in r.getheaders()},
                        data, time.monotonic() - t0)
        except (OSError, http.client.HTTPException) as exc:
            return Resp(0, {"x-error": type(exc).__name__}, repr(exc).encode(),
                        time.monotonic() - t0)
        finally:
            conn.close()

    def grant(self, owner, collection, grantee, level):
        r = self.api("PUT", "/grants", owner if owner != "alice" else "alice",
                     {"owner": owner, "collection": collection,
                      "grantee": grantee, "level": level})
        if r.status != 200 or not (r.json or {}).get("active"):
            raise RuntimeError("grant %s/%s -> %s %s: %s %s" % (
                owner, collection, grantee, level, r.status, r.json))


def standard_stack(name, *, max_connections=24, cost=4):
    """Start the stack and build the standard layout; returns the stack."""
    s = SpikeStack(name, max_connections=max_connections,
                   cfg={"bcrypt_cost": cost})
    s.up()
    s.make_user("bob")
    for login in ("alice", "bob", "agent-1"):
        if login == "agent-1":
            continue   # a bot without an own space has no principal to create
        r = s.req("PROPFIND", "/", login, headers={"Depth": "0"})
        assert r.status == 207, (login, r.status)
    assert s.req("MKCOL", "/alice/contacts/", "alice", mkcol_book("contacts"),
                 XML).status == 201
    assert s.req("MKCALENDAR", "/alice/cal-work/", "alice",
                 mkcalendar("cal-work"), XML).status == 201
    assert s.req("MKCOL", "/bob/bob-book/", "bob", mkcol_book("bob-book"),
                 XML).status == 201
    assert s.req("MKCALENDAR", "/bob/bob-cal/", "bob",
                 mkcalendar("bob-cal"), XML).status == 201
    for coll in ("contacts", "cal-work"):
        s.grant("alice", coll, "bob", "readwrite")
        s.grant("alice", coll, "agent-1", "read")
    return s



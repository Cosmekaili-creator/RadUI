def _split_params(text):
    """Split a parameter section on ';' outside double quotes."""
    out, cur, q = [], "", False
    for ch in text:
        if ch == '"':
            q = not q
        if ch == ";" and not q:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return out


def _split_values(text):
    """Split one parameter value on ',' outside double quotes."""
    out, cur, q = [], "", False
    for ch in text:
        if ch == '"':
            q = not q
        if ch == "," and not q:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return out


def parse_prop(line):
    """``(group, name, [(param, [values])], value)`` of one unfolded line."""
    q, i = False, 0
    for i, ch in enumerate(line):
        if ch == '"':
            q = not q
        if ch == ":" and not q:
            break
    else:
        return ("", line, [], "")
    head, value = line[:i], line[i + 1:]
    parts = _split_params(head)
    name = parts[0]
    group = ""
    if "." in name:
        group, name = name.split(".", 1)
    params = []
    for p in parts[1:]:
        if "=" in p:
            k, v = p.split("=", 1)
            params.append((k, _split_values(v)))
        else:
            params.append(("", [p]))
    return (group, name, params, value)


def projection(text):
    """Normalised multiset (sorted list) of properties: group and property
    names upper-cased, parameter names upper-cased, repeated parameters merged,
    parameter values lower-cased and sorted, value untouched."""
    out = []
    for ln in unfold(text):
        g, n, ps, v = parse_prop(ln)
        merged = {}
        for k, vals in ps:
            merged.setdefault(k.upper(), []).extend(x.lower() for x in vals)
        pk = tuple((k, tuple(sorted(vs))) for k, vs in sorted(merged.items()))
        out.append((g.lower(), n.upper(), pk, v))
    return sorted(out)


def compare_cards(sent, got):
    """``(level, details)``. Levels, best first: ``byte-identical``,
    ``same-lines`` (identical after unfolding, same order; folding differs),
    ``reordered`` (same logical lines, different order), ``semantic`` (equal
    after the projection above: case, parameter order or merging differ),
    ``different`` (a value or property was added, lost or changed)."""
    if sent == got:
        return "byte-identical", []
    a, b = unfold(sent), unfold(got)
    if a == b:
        return "same-lines", []
    if sorted(a) == sorted(b):
        return "reordered", []
    pa, pb = projection(sent), projection(got)
    if pa == pb:
        only_a = [x for x in a if x not in b]
        only_b = [x for x in b if x not in a]
        return "semantic", ["sent: " + x for x in only_a] + \
            ["got:  " + x for x in only_b]
    only_a = [x for x in pa if x not in pb]
    only_b = [x for x in pb if x not in pa]
    return "different", ["sent-only: %r" % (x,) for x in only_a] + \
        ["got-only: %r" % (x,) for x in only_b]


def fold(line, width=75):
    """RFC 6350 folding of one logical line at ``width`` characters."""
    out, first = [], True
    while len(line) > (width if first else width - 1):
        n = width if first else width - 1
        out.append(line[:n])
        line = line[n:]
        first = False
    out.append(line)
    return "\r\n ".join(out)


def put_then_get(s, user, path, text, headers=None):
    p = s.req("PUT", path, user, text, headers or VCF)
    g = s.req("GET", path, user) if p.status in (201, 204) else None
    return p, g


def seed_books_calendars(s, count, kind="book", name="bulk"):
    """Create ``alice/<name>`` and PUT ``count`` fictional items."""
    if kind == "book":
        assert s.req("MKCOL", "/alice/%s/" % name, "alice",
                     mkcol_book(name), XML).status == 201
    else:
        assert s.req("MKCALENDAR", "/alice/%s/" % name, "alice",
                     mkcalendar(name), XML).status == 201
    for i in range(count):
        if kind == "book":
            r = s.req("PUT", "/alice/%s/u%04d.vcf" % (name, i), "alice",
                      card30("u%04d" % i, "Person%04d Test" % i), VCF)
        else:
            r = s.req("PUT", "/alice/%s/e%04d.ics" % (name, i), "alice",
                      event("e%04d" % i, "Event %d" % i), ICS)
        assert r.status == 201, (i, r.status)


def rows_by_name(text):
    """``{NAME: [value, ...]}`` in document order (group prefix ignored)."""
    out = {}
    for ln in unfold(text):
        g, n, ps, v = parse_prop(ln)
        if n.upper() in ("BEGIN", "END"):
            continue
        out.setdefault(n.upper(), []).append(v)
    return out


def same_name_order_stable(sent, got):
    """True when rows of one property name keep their relative order."""
    return rows_by_name(sent) == rows_by_name(got)


def name_order(text):
    """Property names (upper case, group dropped) in document order."""
    return [parse_prop(ln)[1].upper() for ln in unfold(text)
            if parse_prop(ln)[1].upper() not in ("BEGIN", "END")]

// ---- 1. parse + re-serialise every fixture, no edit ------------------------
log("\n## 1. parse + toString() round trip (no edit)");
const fixtures = ["vcard30-groups.vcf", "vcard40-groups.vcf", "event-tzid-quoted.ics", "event-recur-exdate-override.ics", "event-fold-params.ics"];
const roundTrips = {};
for (const f of fixtures) {
  const raw = readFx(f);
  const comp = new ICAL.Component(ICAL.parse(raw));
  const re = comp.toString();
  roundTrips[f] = re;
  const d = diffLogical(raw, re);
  log(`\n### ${f}`);
  show("input   fold stats", foldStats(raw));
  show("output  fold stats", foldStats(re));
  show("output ends with CRLF", re.endsWith("\r\n") ? "yes" : "no (ends with " + JSON.stringify(re.slice(-2)) + ")");
  show("output uses bare LF", /(^|[^\r])\n/.test(re) ? "yes" : "no");
  show("same logical line count", d.sameCount);
  show("identical logical sequence", d.identicalSequence);
  show("property order changed (same set of lines)", d.orderChanged);
  for (const l of d.onlyInA) log("  - only in input : " + trunc(l));
  for (const l of d.onlyInB) log("  + only in output: " + trunc(l));
  // order of property names
  const an = unfold(raw).map(propName), bn = unfold(re).map(propName);
  show("property-name sequence equal", JSON.stringify(an) === JSON.stringify(bn));
  if (JSON.stringify(an) !== JSON.stringify(bn)) { show("  input names", an.join(",")); show("  output names", bn.join(",")); }
}

// ---- 2. vCard specifics: groups, parameters, PHOTO ----------------------------
log("\n## 2. vCard details");
for (const f of ["vcard30-groups.vcf", "vcard40-groups.vcf"]) {
  const raw = readFx(f);
  const comp = new ICAL.Component(ICAL.parse(raw));
  log(`\n### ${f} (version ${comp.getFirstPropertyValue("version")})`);
  for (const p of comp.getAllProperties()) {
    const params = p.jCal[1];
    log("  " + p.name + " type=" + p.type + " params=" + JSON.stringify(params) + " value=" + trunc(JSON.stringify(p.getFirstValue()), 60));
  }
  // Does ical.js keep the group prefix on output?
  const re = comp.toString();
  const groupsIn = unfold(raw).filter((l) => /^[A-Za-z0-9-]+\.[A-Za-z]/.test(l.split(/[;:]/)[0])).map(propName);
  const groupsOut = unfold(re).filter((l) => /^[A-Za-z0-9-]+\.[A-Za-z]/.test(l.split(/[;:]/)[0])).map(propName);
  show("grouped property names in input ", groupsIn.join(","));
  show("grouped property names in output", groupsOut.join(","));
  const photoIn = unfold(raw).find((l) => /^PHOTO/i.test(l));
  const photoOut = unfold(re).find((l) => /^PHOTO/i.test(l));
  show("PHOTO unfolded identical", photoIn === photoOut);
  if (photoIn !== photoOut) { show("  in ", trunc(photoIn, 90)); show("  out", trunc(photoOut, 90)); }
}


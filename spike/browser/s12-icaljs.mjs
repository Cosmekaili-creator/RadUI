/** RFC 5545 unfolding of CRLF/LF text -> logical lines. */
function unfold(text) {
  return text.replace(/\r\n|\r|\n/g, "\n").replace(/\n[ \t]/g, "").split("\n").filter((l) => l !== "");
}
/** Physical lines of a text (no unfolding). */
const physical = (text) => text.split(/\r\n|\n/).filter((l) => l !== "");

function foldStats(text) {
  const lines = physical(text);
  let maxOct = 0, maxChars = 0, over75 = 0, contOver75 = 0, firstOver75 = 0;
  for (const l of lines) {
    const o = octets(l), c = [...l].length;
    maxOct = Math.max(maxOct, o); maxChars = Math.max(maxChars, c);
    if (o > 75) { over75++; if (l.startsWith(" ")) contOver75++; else firstOver75++; }
  }
  return { physicalLines: lines.length, maxOctets: maxOct, maxCodePoints: maxChars, linesOver75Octets: over75, firstLinesOver75: firstOver75, continuationLinesOver75: contOver75 };
}

function propName(logical) {
  // name incl. group, up to first ; or : (outside quotes: names never hold quotes)
  const m = /^([^;:]+)/.exec(logical);
  return m ? m[1] : logical;
}

/** Compare two texts as lists of logical lines. */
function diffLogical(aText, bText) {
  const a = unfold(aText), b = unfold(bText);
  const res = { sameCount: a.length === b.length, identicalSequence: JSON.stringify(a) === JSON.stringify(b), changed: [], onlyInA: [], onlyInB: [], orderChanged: false };
  const bset = new Map(); b.forEach((l) => bset.set(l, (bset.get(l) || 0) + 1));
  const aset = new Map(); a.forEach((l) => aset.set(l, (aset.get(l) || 0) + 1));
  for (const l of a) { if (!bset.get(l)) res.onlyInA.push(l); else bset.set(l, bset.get(l) - 1); }
  for (const l of b) { if (!aset.get(l)) res.onlyInB.push(l); else aset.set(l, aset.get(l) - 1); }
  if (!res.onlyInA.length && !res.onlyInB.length && !res.identicalSequence) res.orderChanged = true;
  return res;
}

function show(title, v) { log("  " + title + ": " + (typeof v === "string" ? v : JSON.stringify(v))); }
const trunc = (s, n = 110) => (s.length > n ? s.slice(0, n) + "..." : s);

// ---- 0. import / integrity ------------------------------------------------
log("# S12 ical.js report (generated by s12-icaljs.mjs)");
const sums = readFileSync(path.join(vendorDir, "SHA256SUMS"), "utf8").trim().split("\n");
for (const l of sums) {
  const [h, f] = l.split(/\s+/);
  const actual = createHash("sha256").update(readFileSync(path.join(vendorDir, f))).digest("hex");
  log(`sha256 ${f}: ${actual === h ? "OK" : "MISMATCH"}`);
}
